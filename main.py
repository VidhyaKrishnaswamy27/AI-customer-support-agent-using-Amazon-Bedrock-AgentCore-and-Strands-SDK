# Implement MemoryHook, a HookProvider subclass that adds long-term memory.
#
# The class needs:
#   __init__(self, actor_id, session_id, memory_client, memory_id)
#     - store all four as instance attributes
#     - call get_namespaces() and store the result as self.namespaces
#
#   retrieve_customer_context(self, event: MessageAddedEvent)
#     - only runs for plain-text user messages (not tool results)
#     - for each strategy namespace, call memory_client.retrieve_memories(
#          memory_id, namespace (formatted with actorId), query, top_k=5)
#     - collect non-empty memory texts tagged with their strategy type
#     - if any memories found, prepend them to the user message as:
#          "Customer Context:\n<memories>\n\n<original_message>"
#
#   save_support_interaction(self, event: AfterInvocationEvent)
#     - walk the message list backwards to find the last plain-text user
#       query and the last assistant response
#     - call memory_client.create_event(memory_id, actor_id, session_id,
#          messages=[(customer_query, "USER"), (agent_response, "ASSISTANT")])
#
#   register_hooks(self, registry: HookRegistry)
#     - register retrieve_customer_context on MessageAddedEvent
#     - register save_support_interaction on AfterInvocationEvent

class MemoryHook(HookProvider):
    """Long-term memory hook for the customer support agent."""

    def __init__(
        self,
        actor_id: str,
        session_id: str,
        memory_client: MemoryClient,
        memory_id: str,
    ):
        # TODO: Store actor_id, session_id, memory_id, memory_client as attributes
        # TODO: Call get_namespaces() and store the result as self.namespaces
        self.actor_id = actor_id
        self.session_id = session_id
        self.memory_client = memory_client
        self.memory_id = memory_id
        self.namespaces = get_namespaces(self.memory_client, self.memory_id)
        logger.info("Namespaces loaded: %s", self.namespaces)

    def retrieve_customer_context(self, event: MessageAddedEvent):
        """Retrieve relevant memories and prepend them to the user message."""
        try:
            last_message = event.agent.messages[-1]
            user_query = next( (block["text"] for block in last_message.get("content", []) if "text" in block), None, ) 
            if last_message["role"] == "user" and user_query:
                retrieved_memories = []
                
                for strategy_type, namespace_template in self.namespaces.items():
                    # Safely handle format variables
                    try:
                        namespace = namespace_template.format(
                            actorId=self.actor_id,
                            sessionId=self.session_id
                        )
                    except Exception:
                        namespace = namespace_template.replace("{actorId}", self.actor_id)

                    try:
                        response = self.memory_client.list_memory_records(
                        memory_id=self.memory_id,
                        namespace=namespace,
                        max_results=5
                        )
                        memories = response.get("memoryRecordSummaries", [])
                        if memories:
                            for memory in memories:
                                content = memory.get("content", {})
                                text_val = content.get("text") if isinstance(content, dict) else None
                                if text_val:
                                    retrieved_memories.append(f"[{strategy_type}] {text_val}")
                    except Exception as e:
                        logger.warning("Failed retrieving memory for namespace %s: %s", namespace, e)

                if retrieved_memories:
                    context_text = "Customer Context:\n" + "\n".join(retrieved_memories) + "\n\n" 
                    last_message["content"] = [{"text": context_text + user_query}]
        except Exception as e:
            logger.error("Error in retrieve_customer_context: %s", e)

    def save_support_interaction(self, event: AfterInvocationEvent):
        """Save the completed turn to memory after the agent responds."""
        # TODO: Implement memory saving
        # Steps:
        #   1. Get messages from event.agent.messages
        #   2. Walk backwards to find the last user query (plain text)
        #      and the last assistant response
        #   3. Call memory_client.create_event() with both messages
        messages = event.agent.messages
        user_query = None
        agent_response = None
        for msg in reversed(messages):
            text = next((block["text"] for block in msg.get("content", []) if "text" in block), None) 
            if msg["role"] == "assistant" and agent_response is None: 
                agent_response = text 
            elif msg["role"] == "user" and user_query is None: 
                user_query = text
            if user_query and agent_response:
                break
        if user_query and agent_response:
            self.memory_client.create_event(
                memory_id=self.memory_id,
                actor_id=self.actor_id,
                session_id=self.session_id,
                messages=[
                (user_query, 'USER'),
                (agent_response, 'ASSISTANT'),
                ],
            )

    def register_hooks(self, registry: HookRegistry) -> None:  # type: ignore
        """Register both memory callbacks."""
        # TODO: Register retrieve_customer_context on MessageAddedEvent
        # TODO: Register save_support_interaction on AfterInvocationEvent
        registry.add_callback(MessageAddedEvent, self.retrieve_customer_context)
        registry.add_callback(AfterInvocationEvent, self.save_support_interaction)


# --- TODO 6 - Knowledge Base Tool ----------------------------------------------
# Implement search_knowledge_base(query) using the @tool decorator.
#
# Steps:
#   1. Guard: if KB_ID is empty return "Knowledge base not configured."
#   2. Call _bedrock_runtime.retrieve(
#          knowledgeBaseId=KB_ID,
#          retrievalQuery={"text": query}
#      )
#   3. Extract resp["retrievalResults"]; return a message if empty
#   4. Join the text chunks with "\n---\n" and return the result
#
# The docstring is the tool description - the model uses it to decide when
# to call this tool, so keep it clear and accurate.

@tool
def search_knowledge_base(query: str) -> str:
    """
    Search the Amazon product catalog and support knowledge base.
    Use this for product specifications, return policies, warranty
    information, loyalty program details, and order status definitions.

    Args:
        query: The question or topic to search for

    Returns:
        Relevant information retrieved from the knowledge base
    """
    if not KB_ID:
        return "Knowledge base not configured."
    
    try:
        resp = _bedrock_runtime.retrieve(
            knowledgeBaseId=KB_ID,
            retrievalQuery={"text": query}
        )
        results = resp.get("retrievalResults", [])
        if not results:
            return "No relevant information found in the knowledge base."
        
        # Extract text content from each result chunk
        extracted = []
        for result in results:
            text = result.get("content", {}).get("text", "")
            if text:
                extracted.append(text)
                
        return "\n---\n".join(extracted) if extracted else "No text found in knowledge base results."
    except Exception as e:
        logger.error("Error searching knowledge base: %s", e)
        return f"Error retrieving from knowledge base: {str(e)}"


# --- TODO 7 - Loyalty Discount Tool (Code Interpreter) -------------------------
# Implement calculate_loyalty_discount() using the @tool decorator.
#
# The tool must:
#   1. Build a self-contained Python code string that:
#        - Defines earn_rates: {"standard": 1, "device": 2, "fresh": 5}
#        - Defines tier_rates: {"Silver": 0.00, "Gold": 0.10, "Platinum": 0.15}
#        - Calculates points_redeemed (floor to nearest 500, cap at 50% of order)
#        - Calculates tier_discount (applied to subtotal after points)
#        - Calculates final_total, total_savings, points_earned, remaining_points
#        - Prints a JSON result dict
#   2. Execute the code with code_session(REGION).invoke("executeCode", {...})
#      using language="python" and clearContext=True
#   3. Return the first result event as a JSON string
#   4. Include a fallback that computes only the tier discount if the
#      Code Interpreter is unavailable

@tool
def calculate_loyalty_discount(
    loyalty_points: int,
    tier: str,
    order_total: float,
    product_category: str = "standard",
) -> str:
    # Build a self-contained Python script for the code interpreter.
    code = f"""
    import json

    earn_rates = {{"standard": 1, "device": 2, "fresh": 5}}
    tier_rates = {{"Silver": 0.00, "Gold": 0.10, "Platinum": 0.15}}

    loyalty_points = int({loyalty_points})
    order_total = float({order_total})
    product_category = "{product_category}"
    tier = "{tier}"

    points_earned = earn_rates.get(product_category, 1)
    points_redeemed = min(int(order_total * 0.5), int((loyalty_points // 500) * 500))
    subtotal_after_points = max(order_total - points_redeemed, 0.0)
    tier_discount = tier_rates.get(tier, 0.0)
    final_total = round(subtotal_after_points * (1 - tier_discount), 2)
    total_savings = round(order_total - final_total, 2)
    remaining_points = max(loyalty_points - points_redeemed + points_earned, 0)

    result = {{
        "points_redeemed": points_redeemed,
        "tier_discount": tier_discount,
        "final_total": final_total,
        "total_savings": total_savings,
        "points_earned": points_earned,
        "remaining_points": remaining_points,
    }}
    print(json.dumps(result))
    """

    try:
        session = code_session(REGION)
        resp = session.invoke(
                "executeCode",
                {"code": code, "language": "python", "clearContext": True},
            )
        result = resp.get("result") if isinstance(resp, dict) else resp
        if isinstance(result, list) and result:
            result = result[0]
        if isinstance(result, dict):
            return json.dumps(result)
        return json.dumps({"raw_response": str(resp)})

    except Exception:
        tier_rates = {"Silver": 0.00, "Gold": 0.10, "Platinum": 0.15}
        tier_discount = tier_rates.get(tier, 0)
        final_total = order_total - (order_total * tier_discount)
        return json.dumps({"final_total": final_total, "tier_discount": tier_discount})


